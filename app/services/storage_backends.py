"""Optional delivery backends: Email, Google Drive, SFTP."""
import json
import smtplib
from email.message import EmailMessage
from pathlib import Path


def send_email(settings: dict, filepath: Path, filename: str, device: dict) -> str:
    if settings.get("smtp_enabled") != "1":
        return "email disabled"
    try:
        host = settings.get("smtp_host", "")
        port = int(settings.get("smtp_port") or 587)
        user = settings.get("smtp_user", "")
        password = settings.get("smtp_password", "")
        sender = settings.get("smtp_from") or user
        recipients = [x.strip() for x in settings.get("smtp_to", "").split(",") if x.strip()]
        if not host or not recipients:
            return "email: missing host or recipient"

        msg = EmailMessage()
        msg["Subject"] = f"[Savcon] Backup {device['name']} - {filename}"
        msg["From"] = sender
        msg["To"] = ", ".join(recipients)
        msg.set_content(
            f"Configuration backup for device {device['name']} ({device['host']}).\n"
            f"File: {filename}\nGenerated by Savcon Manager."
        )
        data = Path(filepath).read_bytes()
        subtype = "plain"
        msg.add_attachment(data, maintype="text", subtype=subtype, filename=filename)

        if settings.get("smtp_tls") == "1":
            with smtplib.SMTP(host, port, timeout=20) as smtp:
                smtp.starttls()
                if user:
                    smtp.login(user, password)
                smtp.send_message(msg)
        else:
            with smtplib.SMTP_SSL(host, port, timeout=20) as smtp:
                if user:
                    smtp.login(user, password)
                smtp.send_message(msg)
        return "email: ok"
    except Exception as exc:
        return f"email: failed ({exc})"


def send_sftp(settings: dict, filepath: Path, filename: str, device: dict) -> str:
    if settings.get("sftp_enabled") != "1":
        return "sftp disabled"
    try:
        import paramiko

        host = settings.get("sftp_host", "")
        port = int(settings.get("sftp_port") or 22)
        user = settings.get("sftp_user", "")
        password = settings.get("sftp_password", "")
        base = settings.get("sftp_path") or "/"
        if not host or not user:
            return "sftp: missing host or user"
        client = paramiko.SSHClient()
        client.set_missing_host_key_policy(paramiko.AutoAddPolicy())
        client.connect(host, port=port, username=user, password=password, timeout=20)
        sftp = client.open_sftp()
        try:
            folder = f"{base.rstrip('/')}/{device['name']}"
            try:
                sftp.stat(folder)
            except IOError:
                parts = folder.strip("/").split("/")
                current = ""
                for part in parts:
                    current += "/" + part
                    try:
                        sftp.stat(current)
                    except IOError:
                        sftp.mkdir(current)
            sftp.put(str(filepath), f"{folder}/{filename}")
        finally:
            sftp.close()
            client.close()
        return "sftp: ok"
    except Exception as exc:
        return f"sftp: failed ({exc})"


def send_gdrive(settings: dict, filepath: Path, filename: str, device: dict) -> str:
    if settings.get("gdrive_enabled") != "1":
        return "gdrive disabled"
    try:
        from google.oauth2 import service_account
        from googleapiclient.discovery import build
        from googleapiclient.http import MediaFileUpload

        creds_json = settings.get("gdrive_credentials", "").strip()
        if not creds_json:
            return "gdrive: missing service account JSON"
        info = json.loads(creds_json)
        scopes = ["https://www.googleapis.com/auth/drive.file"]
        creds = service_account.Credentials.from_service_account_info(info, scopes=scopes)
        service = build("drive", "v3", credentials=creds, cache_discovery=False)
        folder_id = settings.get("gdrive_folder_id", "").strip() or None
        metadata = {"name": filename}
        if folder_id:
            metadata["parents"] = [folder_id]
        media = MediaFileUpload(str(filepath), mimetype="text/plain", resumable=False)
        service.files().create(body=metadata, media_body=media, fields="id").execute()
        return "gdrive: ok"
    except Exception as exc:
        return f"gdrive: failed ({exc})"
